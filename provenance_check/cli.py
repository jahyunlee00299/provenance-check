"""provenance-check CLI: check | hash | init.  Exit 0 clean / 1 violations / 2 cannot check."""
from __future__ import annotations

import argparse
import json
import math
import os
import sys
import tomllib
from pathlib import Path

from provenance_check.core import (CannotCheck, Report, check_declaration,
                                   load_value_source, sha256_of)


def _cannot(reason: str) -> int:
    print(f"provenance-check: cannot check — {reason}", file=sys.stderr)
    return 2


def _render_text(rep: Report) -> str:
    lines: list[str] = []
    for f in rep.findings:
        lines.append(f"[{f['rule']}] {f['status']} ({f['confidence']}) {f['constant']}")
        lines.append(f"    {f['message']}")
        if "fix" in f:
            lines.append(f"    fix: {f['fix']['applicability']}/{f['fix']['apply']}")
    lines.append(f"provenance-check: {rep.violations} violation(s), "
                 f"{rep.cannot_check} cannot-check across {rep.checked} declared constant(s)")
    return "\n".join(lines)


def _cmd_check(args: argparse.Namespace) -> int:
    paths = args.paths or ["provenance.toml"]
    merged = Report()
    try:
        for p in paths:
            rep = check_declaration(Path(p))
            merged.findings.extend(rep.findings)
            merged.checked += rep.checked
    except CannotCheck as e:
        return _cannot(str(e))
    if args.format == "json":
        print(json.dumps({"findings": merged.findings, "summary": merged.summary()},
                         indent=2, ensure_ascii=False))
    else:
        print(_render_text(merged))
    return merged.exit_code


def _cmd_hash(args: argparse.Namespace) -> int:
    p = Path(args.file)
    if not p.is_file():
        return _cannot(f"file not found: {p}")
    print(sha256_of(p))
    return 0


def _leaves(node, prefix=""):
    if isinstance(node, dict):
        for k, v in node.items():
            yield from _leaves(v, f"{prefix}{k}.")
    elif isinstance(node, (int, float)) and not isinstance(node, bool) and math.isfinite(node):
        yield prefix[:-1], node


def _q(s: str) -> str:
    return json.dumps(s, ensure_ascii=False)


def _cmd_init(args: argparse.Namespace) -> int:
    out, params, source = Path(args.out), Path(args.params), Path(args.source)
    if out.exists():
        return _cannot(f"refusing to overwrite existing {out}")
    if not source.is_file():
        return _cannot(f"source file not found: {source}")
    try:
        tree = load_value_source(params)
    except (OSError, ValueError, tomllib.TOMLDecodeError) as e:
        return _cannot(f"cannot read params {params}: {e}")
    leaves = list(_leaves(tree))
    if not leaves:
        return _cannot(f"no numeric leaves in {params}")
    outdir = out.resolve().parent

    def rel(p: Path) -> str:
        return Path(os.path.relpath(p.resolve(), outdir)).as_posix()

    digest = sha256_of(source)
    lines = ["# DRAFT generated by `provenance-check init`. Fill every TODO;",
             "# the untouched draft fails `check` on purpose.",
             "[provenance]",
             "expect = [" + ", ".join(_q(k) for k, _ in leaves) + "]", ""]
    for k, v in leaves:
        lines += [f"[constants.{_q(k)}]",
                  f"value = {v!r}",
                  f"source = {_q(rel(source))}",
                  f"sha256 = {_q(digest)}",
                  'measured_at = "TODO"',
                  f"instrument = {_q(args.instrument or 'TODO')}",
                  f"value_ref = {_q(rel(params) + ':' + k)}", ""]
    out.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"provenance-check: wrote draft {out} with {len(leaves)} constant(s); "
          "fill measured_at/instrument, then run `provenance-check check`")
    return 0


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="provenance-check", description=__doc__)
    sub = ap.add_subparsers(dest="cmd", required=True)
    c = sub.add_parser("check", help="check a provenance.toml")
    c.add_argument("paths", nargs="*", help="declaration file(s) (default ./provenance.toml)")
    c.add_argument("--format", choices=["text", "json"], default="text")
    c.set_defaults(fn=_cmd_check)
    h = sub.add_parser("hash", help="print sha256 of a file")
    h.add_argument("file")
    h.set_defaults(fn=_cmd_hash)
    i = sub.add_parser("init", help="write a DRAFT declaration from a params file")
    i.add_argument("--params", required=True)
    i.add_argument("--source", required=True)
    i.add_argument("--out", default="provenance.toml")
    i.add_argument("--instrument")
    i.set_defaults(fn=_cmd_init)
    args = ap.parse_args(argv)
    return args.fn(args)


if __name__ == "__main__":
    sys.exit(main())
